package com.jinlin.mysqlandredis.redis.datastructure;

/**
 * Redis 数据结构篇 07: Redis 选用跳表 (Skiplist) 而非 B+ 树或红黑树的根本技术考量
 *
 * 面试真题：Redis 为什么使用跳表而不是用 B+ 树？
 *
 * 核心考点与原理（结合 Redis 作者 antirez 官方阐述）：
 * 1. 物理介质差异：内存寻道 vs 磁盘 I/O 瓶颈
 *    - B+ 树的设计初衷：专为【机械硬盘 / 固态硬盘】等外存设备设计。其“多叉矮胖”的形态将节点大小对齐为 4KB/16KB 磁盘物理页，
 *      旨在通过极低的树高度（3~4 层）将数千万数据的磁盘随机寻道 I/O 降至最低；
 *    - Redis 的物理本质：纯【内存数据库】。内存寻道是纳秒级（~100ns），没有磁盘旋转寻道瓶颈，
 *      因此无需维护庞大的 4KB/16KB 页节点，不需要引入 B+ 树的节点页分裂与合并机制。
 *
 * 2. 范围查询 (Range Query) 与迭代的极致优雅：
 *    - ZSet 的核心业务操作是 ZRANGEBYSCORE, ZREVRANGE 等范围过滤与排名查询；
 *    - 跳表查找范围：先以 O(logN) 寻道至区间下界的起始节点，之后直接沿着最底层的链表（带 forward/backward 指针）
 *      顺序向前/向后线性扫描即可，CPU 缓存连续命中，执行开销极低；
 *    - B+ 树虽然叶子节点相连，但在纯内存中维护阶数复杂的树结构性价比极低；红黑树做范围查询则需要中序遍历上下回溯，性能更差。
 *
 * 3. 内存开销与碎片对比：
 *    - 跳表在 p=0.25 策略下，平均每个节点仅需 1.33 个指针，没有内部空闲 slot 碎片；
 *    - B+ 树节点通常处于 50%~100% 的填充状态，在内存中会产生大量未使用的空洞内存碎片；
 *    - 红黑树每个节点固定需要 3 个指针（父节点、左孩子、右孩子）+ 1 个颜色标志位，内存开销更大。
 *
 * 4. 实现与维护复杂度：
 *    - 平衡树（红黑树、AVL 树、B+ 树）在插入/删除节点时需要复杂的旋转、重新着色、节点分裂与合并；
 *    - 跳表通过掷骰子随机层高实现概率平衡，插入/删除仅需局部调整前后指针，代码简单清晰、Bug 率极低。
 */
